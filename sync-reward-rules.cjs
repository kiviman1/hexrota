/* Keep the browser wrapper in sync with the Unity-readable canonical JSON. */
const fs=require('node:fs');
const rules=JSON.parse(fs.readFileSync(__dirname+'/dist/reward-rules.json','utf8'));
require('./dist/rewards.js').validateRules(rules);
const text='/* Generated by sync-reward-rules.cjs from reward-rules.json. */\nwindow.HEX_REWARD_RULES = '+JSON.stringify(rules,null,2)+';\n';
const target=__dirname+'/dist/reward-rules.js';
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==text)throw new Error('Reward rule wrapper is stale');}
else fs.writeFileSync(target,text);
