using System;
using Hexrota.UnityClient.Presentation;
using UnityEditor;
using UnityEngine;
using UnityEngine.UI;

namespace Hexrota.UnityClient.Editor
{
    // Rebuilds only the authored home environment from independently editable assets.
    public static class CastleHomeLayerBuilder
    {
        private const string Home = "Assets/Hexrota/Resources/CastleHome/";
        private const string Prefab = Home + "CastleHome.prefab";
        private const string WaterMaterial = "Assets/Hexrota/Art/CastleHome/WaterFlow.mat";

        [MenuItem("Hexrota/Home/Rebuild Independent Home Layers")]
        public static void Rebuild()
        {
            string[] required = { "Atmosphere/Sky", "Atmosphere/Cloud", "Atmosphere/FloatingIsland", "Atmosphere/Waterfall", "Atmosphere/GardenGround", "Atmosphere/StoneBridge", "Layers/CastleWithoutCharacters", "Layers/FlagCloth", "Layers/GoldFlagPole", "Characters/HenBody", "Characters/HenWing", "Characters/Chick", "Foreground/Flowerbed", "Foreground/Fence" };
            foreach (var name in required) Sprite(name);
            foreach (var name in new[] { "LeftTowerNoPole", "CentralTower", "RightTower", "CastleBody" }) CastlePartSprite(name);
            var shader = AssetDatabase.LoadAssetAtPath<Shader>("Assets/Hexrota/Art/CastleHome/WaterFlow.shader");
            if (shader == null) throw new InvalidOperationException("WaterFlow shader is missing.");
            var material = AssetDatabase.LoadAssetAtPath<Material>(WaterMaterial);
            if (material == null) { material = new Material(shader); AssetDatabase.CreateAsset(material, WaterMaterial); }
            else { material.shader = shader; EditorUtility.SetDirty(material); }
            var root = PrefabUtility.LoadPrefabContents(Prefab);
            try
            {
                var env = root.transform.Find("MenuLayout/Environment");
                var castle = env.Find("Coop");
                var background = env.Find("Background").GetComponent<Image>();
                if (env == null || castle == null || background == null) throw new InvalidOperationException("Home prefab hierarchy changed.");
                // Only remove groups generated by this builder; original UI and controls stay untouched.
                foreach (var name in new[] { "FarClouds", "FarIslands", "Waterfalls", "Ground", "Foreground" })
                {
                    var existing = env.Find(name); if (existing != null) UnityEngine.Object.DestroyImmediate(existing.gameObject);
                }
                foreach (var name in new[] { "CentralTower", "RightTower", "CastleBody", "LeftFlagPole", "LeftFlagCloth", "RightFlagPole", "RightFlagCloth", "HenAnchor", "ChickAnchor" })
                {
                    var existing = castle.Find(name); if (existing != null) UnityEngine.Object.DestroyImmediate(existing.gameObject);
                }
                var oldFlag = castle.GetComponent<CastleHomeFlagCloth>();
                if (oldFlag != null) UnityEngine.Object.DestroyImmediate(oldFlag);
                background.sprite = Sprite("Atmosphere/Sky");
                castle.GetComponent<Image>().sprite = CastlePartSprite("LeftTowerNoPole");
                CastlePart(castle, "CentralTower");
                CastlePart(castle, "RightTower");
                CastlePart(castle, "CastleBody");
                
                var clouds = Group(env, "FarClouds", castle);
                ImageLayer(clouds, "CloudFarLeft", "Atmosphere/Cloud", new Vector2(.06f,.76f), new Vector2(265,90), .78f, new Vector2(15,0), .013f, 0f);
                ImageLayer(clouds, "CloudFarRight", "Atmosphere/Cloud", new Vector2(.93f,.68f), new Vector2(250,85), .75f, new Vector2(-20,0), .019f, 1.3f);
                ImageLayer(clouds, "CloudNearLeft", "Atmosphere/Cloud", new Vector2(.03f,.43f), new Vector2(250,85), .7f, new Vector2(24,0), .025f, .5f);
                ImageLayer(clouds, "CloudNearRight", "Atmosphere/Cloud", new Vector2(.98f,.38f), new Vector2(250,85), .7f, new Vector2(-27,0), .022f, 2f);
                var islands = Group(env, "FarIslands", castle);
                ImageLayer(islands, "IslandDistantLeft", "Atmosphere/FloatingIsland", new Vector2(.05f,.69f), new Vector2(95,70), .72f, new Vector2(2,0), .009f, 2f);
                ImageLayer(islands, "IslandDistantRight", "Atmosphere/FloatingIsland", new Vector2(.96f,.73f), new Vector2(105,75), .72f, new Vector2(-2,0), .01f, 3f);
                ImageLayer(islands, "IslandLeft", "Atmosphere/FloatingIsland", new Vector2(.05f,.56f), new Vector2(220,150), 1, new Vector2(4,1), .012f, .5f);
                var rightIsland = ImageLayer(islands, "IslandRight", "Atmosphere/FloatingIsland", new Vector2(.96f,.57f), new Vector2(225,160), 1, new Vector2(-5,1), .011f, 1.2f);
                rightIsland.rectTransform.localScale = new Vector3(-1,1,1);
                ImageLayer(islands, "DistantBridge", "Atmosphere/StoneBridge", new Vector2(.86f,.48f), new Vector2(140,70), .9f, Vector2.zero, 0f, 0f);
                var water = Group(env, "Waterfalls", castle);
                var leftWater = ImageLayer(water, "WaterfallLeft", "Atmosphere/Waterfall", new Vector2(.055f,.47f), new Vector2(72,174), .95f, Vector2.zero, 0f, 0f);
                var rightWater = ImageLayer(water, "WaterfallRight", "Atmosphere/Waterfall", new Vector2(.94f,.47f), new Vector2(75,178), .95f, Vector2.zero, 0f, 0f);
                leftWater.material = rightWater.material = material;
                var ground = Group(env, "Ground", castle);
                ImageLayer(ground, "StonePathAndMeadow", "Atmosphere/GardenGround", new Vector2(.5f,.205f), new Vector2(700,350), 1, Vector2.zero, 0, 0);
                
                var leftPole = CastleChild(castle, "LeftFlagPole", "Layers/GoldFlagPole", .195f, .805f, .055f, .125f);
                leftPole.preserveAspect = true;
                var leftFlag = CastleChild(castle, "LeftFlagCloth", "Layers/FlagCloth", .305f, .815f, .225f, .085f);
                leftFlag.gameObject.AddComponent<CastleHomeFlagCloth>();
                var rightPole = CastleChild(castle, "RightFlagPole", "Layers/GoldFlagPole", .768f, .714f, .050f, .15f);
                rightPole.preserveAspect = true;
                var rightFlag = CastleChild(castle, "RightFlagCloth", "Layers/FlagCloth", .84f, .755f, .16f, .065f);
                var rightWave = rightFlag.gameObject.AddComponent<CastleHomeFlagCloth>();
                var rightWaveData = new SerializedObject(rightWave);
                rightWaveData.FindProperty("phaseOffset").floatValue = 1.5f;
                rightWaveData.ApplyModifiedPropertiesWithoutUndo();
                var hen = Character(castle, "HenAnchor", "Characters/HenBody", .33f, .20f, .22f, .23f);
                var henMotion = hen.gameObject.AddComponent<CastleHomeLayerMotion>();
                henMotion.cyclesPerSecond = .35f; henMotion.breathing = .018f; henMotion.rotation = 1.1f;
                var wing = Character(hen.transform, "WingAnchor", "Characters/HenWing", .325f, .373f, .47f, .415f);
                var wingMotion = wing.gameObject.AddComponent<CastleHomeLayerMotion>();
                wingMotion.cyclesPerSecond = .42f; wingMotion.rotation = 5f; wingMotion.phase = 1f;
                var chick = Character(castle, "ChickAnchor", "Characters/Chick", .78f, .16f, .13f, .15f);
                var chickMotion = chick.gameObject.AddComponent<CastleHomeLayerMotion>();
                chickMotion.cyclesPerSecond = .4f; chickMotion.breathing = .025f; chickMotion.rotation = 2f; chickMotion.phase = 1f;
                var foreground = Group(env, "Foreground", null);
                ImageLayer(foreground, "FlowersLeft", "Foreground/Flowerbed", new Vector2(.02f,.11f), new Vector2(150,72), 1, Vector2.zero, 0, 0);
                var flowersRight = ImageLayer(foreground, "FlowersRight", "Foreground/Flowerbed", new Vector2(.98f,.10f), new Vector2(140,67), 1, Vector2.zero, 0, 0);
                flowersRight.rectTransform.localScale = new Vector3(-1,1,1);
                ImageLayer(foreground, "FenceLeft", "Foreground/Fence", new Vector2(.08f,.25f), new Vector2(85,55), 1, Vector2.zero, 0, 0);
                var play = root.transform.Find("MenuLayout/PlayArea/PlayButton");
                var oldGlints = play.Find("BrassGlints"); if (oldGlints != null) UnityEngine.Object.DestroyImmediate(oldGlints.gameObject);
                var glints = NewRect(play, "BrassGlints"); Stretch(glints); glints.gameObject.AddComponent<CanvasRenderer>();
                glints.gameObject.AddComponent<CastleHomeBrassGlints>().raycastTarget = false;
                foreach (string name in new[] { "Events", "Missions", "Rewards" })
                {
                    var icon = root.transform.Find("MenuLayout/SideActions/" + name + "/Icon");
                    if (icon == null) continue;
                    var motion = icon.GetComponent<CastleHomeLayerMotion>() ?? icon.gameObject.AddComponent<CastleHomeLayerMotion>();
                    motion.travel = new Vector2(0, 1.2f); motion.cyclesPerSecond = .22f; motion.rotation = 1f;
                    motion.phase = name == "Events" ? 0 : name == "Missions" ? 2f : 4f;
                }
                Canvas.ForceUpdateCanvases();
                foreach (var anchor in root.GetComponentsInChildren<CastleHomeSpriteAnchor>(true)) anchor.Fit();
                PrefabUtility.SaveAsPrefabAsset(root, Prefab);
            }
            finally { PrefabUtility.UnloadPrefabContents(root); }
            AssetDatabase.SaveAssets(); AssetDatabase.Refresh();
            Debug.Log("Castle home independent layers rebuilt.");
        }

        private static Sprite Sprite(string name)
        {
            var sprite = AssetDatabase.LoadAssetAtPath<Sprite>(Home + name + ".png");
            if (sprite == null) throw new InvalidOperationException("Missing home sprite: " + name);
            return sprite;
        }
        private static Sprite CastlePartSprite(string name)
        {
            var sprite = AssetDatabase.LoadAssetAtPath<Sprite>("Assets/Hexrota/Art/CastleHome/LayerCandidates/" + name + ".png");
            if (sprite == null) throw new InvalidOperationException("Missing castle part: " + name);
            return sprite;
        }
        private static void CastlePart(Transform parent, string name)
        {
            var rect = NewRect(parent, name); Stretch(rect);
            var image = rect.gameObject.AddComponent<Image>();
            image.sprite = CastlePartSprite(name); image.preserveAspect = true; image.raycastTarget = false;
        }
        private static RectTransform NewRect(Transform parent, string name)
        {
            var go = new GameObject(name, typeof(RectTransform)); go.layer = parent.gameObject.layer; go.transform.SetParent(parent, false);
            return (RectTransform)go.transform;
        }
        private static void Stretch(RectTransform rect)
        {
            rect.anchorMin = Vector2.zero; rect.anchorMax = Vector2.one; rect.offsetMin = rect.offsetMax = Vector2.zero;
        }
        private static RectTransform Group(Transform env, string name, Transform before)
        {
            var rect = NewRect(env, name); Stretch(rect);
            if (before != null) rect.SetSiblingIndex(before.GetSiblingIndex());
            return rect;
        }
        private static Image ImageLayer(Transform parent, string name, string asset, Vector2 anchor, Vector2 size, float alpha, Vector2 travel, float speed, float phase)
        {
            var rect = NewRect(parent, name); rect.anchorMin = rect.anchorMax = anchor; rect.sizeDelta = size;
            var image = rect.gameObject.AddComponent<Image>(); image.sprite = Sprite(asset); image.preserveAspect = true;
            image.color = new Color(1, 1, 1, alpha); image.raycastTarget = false;
            if (speed > 0f) { var motion = rect.gameObject.AddComponent<CastleHomeLayerMotion>(); motion.travel = travel; motion.cyclesPerSecond = speed; motion.phase = phase; }
            return image;
        }
        private static Image CastleChild(Transform parent, string name, string asset, float x, float y, float width, float height)
        {
            var rect = NewRect(parent, name);
            var image = rect.gameObject.AddComponent<Image>(); image.sprite = Sprite(asset); image.preserveAspect = false; image.raycastTarget = false;
            var anchor = rect.gameObject.AddComponent<CastleHomeSpriteAnchor>(); anchor.x = x; anchor.y = y; anchor.sizeInSprite = new Vector2(width, height); anchor.Fit();
            return image;
        }
        private static Image Character(Transform parent, string name, string asset, float x, float y, float width, float height)
        {
            var holder = NewRect(parent, name);
            var anchor = holder.gameObject.AddComponent<CastleHomeSpriteAnchor>();
            anchor.x = x; anchor.y = y; anchor.sizeInSprite = new Vector2(width, height); anchor.Fit();
            var visual = NewRect(holder, "Visual"); Stretch(visual);
            var image = visual.gameObject.AddComponent<Image>();
            image.sprite = Sprite(asset); image.raycastTarget = false; image.preserveAspect = false;
            return image;
        }
    }
}
