const fs=require('node:fs');global.window={};require('./dist/engine.js');const HexMatch=window.HexMatch;
function rng(seed){let x=seed>>>0;return()=>{x^=x<<13;x^=x>>>17;x^=x<<5;return(x>>>0)/4294967296;};}
function shape(kind){let cells=[];for(let q=-3;q<=3;q++)for(let r=-3;r<=3;r++)if(Math.max(Math.abs(q),Math.abs(r),Math.abs(q+r))<=3){if(kind===19&&Math.max(Math.abs(q),Math.abs(r),Math.abs(q+r))>2)continue;if(kind===23&&(Math.abs(q)>2||Math.abs(r)>2))continue;if(kind===29&&Math.abs(q)>2)continue;cells.push({q,r,layers:1});}return cells.sort((a,b)=>(a.r+a.q/2)-(b.r+b.q/2)||a.q-b.q);}
function initialBoard(level,random){const game=new HexMatch({...level,initial:level.cells.map(()=>1)});for(let attempt=0;attempt<20000;attempt++){game.values=level.cells.map(()=>level.palette[Math.floor(random()*level.palette.length)]);if(!game.findMatches().length&&game.legalMoves().length>=2)return game.values.slice();}throw Error('No initial board');}
function solve(level,maxDepth,width=10){
 const first=new HexMatch(level),goal=first.remainingLayers;
 let beam=[{game:first,route:[],rank:0}];
 for(let depth=0;depth<maxDepth;depth++){
  const children=[],seen=new Set();
  for(const node of beam){
   for(const pair of node.game.legalMoves()){
    const next=node.game.clone();next.swap(...pair);
    const route=node.route.concat([pair]);
    if(next.remainingLayers===0)return{route,score:next.score,turn:depth+1};
    if(next.status==='lost')continue;
    const hash=next.values.join('')+'|'+next.layers.join('')+'|'+next.specials.join(',')+'|'+next.rngState;
    if(seen.has(hash))continue;seen.add(hash);
    const progress=goal-next.remainingLayers;
    const rank=progress*100+next.covered*30+next.score*.06;
    children.push({game:next,route,rank});
   }
  }
  children.sort((a,b)=>b.rank-a.rank);beam=children.slice(0,width);
  if(!beam.length)return null;
 }
 return null;
}
function randomBaseline(level,trials=60){let wins=0;const random=rng(9107+level.id*917);for(let t=0;t<trials;t++){const g=new HexMatch(level);while(g.status==='playing'){const legal=g.legalMoves();if(!legal.length)break;g.swap(...legal[Math.floor(random()*legal.length)]);}if(g.status==='won')wins++;}return wins/trials;}
