import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context = {window: {}, performance};
vm.createContext(context);
for (const name of ['levels.js', 'engine.js']) vm.runInContext(fs.readFileSync(new URL('dist/' + name, import.meta.url), 'utf8'), context);
const {HexEngine, HEX_LEVELS} = context.window;
const fixture = {cells:[{q:0,r:0,value:1,cap:2},{q:1,r:0,value:2,cap:1},{q:2,r:0,value:3,cap:1}], target:7, solution:[2,1,0]};
const e = new HexEngine(fixture);
assert.equal(e.add(0).ok,true);
assert.equal(e.add(2).reason,'neighbor');
assert.equal(e.sum,1);
assert.equal(e.add(1).ok,true);
assert.equal(e.add(0).ok,true);
assert.equal(e.counts[0],2);
assert.equal(e.add(1).reason,'used');
assert.equal(e.status,'stuck');
assert.equal(e.hint().type,'undo');
assert.equal(e.undo(),true);
assert.equal(e.counts[0],1);
assert.equal(e.covered,2);
assert.equal(e.sum,3);
e.reset();
assert.equal(e.path.length,0);
assert.equal(e.sum,0);
assert.equal(e.undo(),false);
assert.equal(e.add(2).ok,true,'Any cell can start a route');
assert.equal(e.add(1).ok,true);
assert.equal(e.add(0).ok,true);
assert.equal(e.status,'stuck','All green with a low sum is not victory');
assert.equal(e.hint().type,'undo');
const over = new HexEngine({...fixture,target:2});
over.add(2);
assert.equal(over.status,'over');
assert.equal(over.add(1).reason,'over');
over.undo();
assert.equal(over.status,'playing');
assert.throws(() => new HexEngine(fixture,[0,2]));
const alternate = new HexEngine({cells:fixture.cells.map(c=>({...c,cap:1})),target:6,solution:[0,1,2]},[2]);
const snapshot = JSON.stringify(alternate.state);
const hint = alternate.hint();
assert.equal(hint.type,'next');
assert.equal(hint.index,1);
assert.equal(JSON.stringify(alternate.state),snapshot,'Hints cannot mutate gameplay state');
for (const [i, level] of HEX_LEVELS.entries()) {
  const game = new HexEngine(level);
  for (const index of level.solution) {
    const before = JSON.stringify(game.state);
    const suggested = game.hint();
    assert.equal(suggested.type,'next',`Level ${i+1} has a hint for every solution prefix`);
    assert.equal(suggested.index,index);
    assert.equal(JSON.stringify(game.state),before);
    assert.equal(game.add(index).ok,true,`Level ${i+1}: valid solution step`);
  }
  assert.equal(game.status,'won',`Level ${i+1} completes`);
  assert.equal(game.covered,level.cells.length);
  assert.equal(game.sum,level.target);
  assert.equal(game.hint().type,'none');
  assert.equal(game.add(0).reason,'won');
  const restored = new HexEngine(level,level.solution);
  assert.equal(restored.status,'won');
  game.undo();
  assert.notEqual(game.status,'won');
}
console.log('Engine checks passed: 10 solutions, hint prefixes, restore, adjacency, capacity, undo, overshoot and victory.');
